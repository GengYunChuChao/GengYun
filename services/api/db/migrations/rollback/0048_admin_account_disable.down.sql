-- 迁移 0048 回滚：删掉 `public.disable_admin_account(...)` 与 `public.enable_admin_account(...)`
-- =============================================================================
--
-- 回滚到 0048 之前的样子（没有这两条函数；`admin_accounts` / `admin_sessions` /
-- `admin_audit_events` 的表结构、行、索引、触发器一律不动）。
--
-- ⛔ 不删审计行，也不数它们来拒绝回滚
-- ---------------------------------------------------------------
-- 与 `rollback/0047_*.down.sql`（那里用 `G0019` 拦回滚）**刻意不同**，理由有三条：
--   1. 这两条函数删掉之后，已经落库的 `admin_account.disable` / `admin_account.enable` 审计行
--      **不是「有行无出处」**：它们记录的是**已经发生过的**状态迁移（账号当时确实被停用/恢复），
--      而 `admin_accounts.state` 与 `admin_sessions.revoked_at` 是这些事实的**另一份在册证据**。
--      删函数不会让那条审计变成假的 —— 恰恰相反，审计与账号行仍然互相对得上。
--   2. 把它们数出来当拦门条件，会让「回滚一次停用功能」变成「必须先证明从没人用过它」——
--      一次演练就永久锁死回滚路径。`0047` 之所以敢拦，是因为那条审计的唯一写入点就是被删的
--      函数（删了就再也写不进第二行），而本节这两条函数**不承载唯一事实**。
--   3. `admin_audit_events` 是 append-only（`0017:113-115` 把 UPDATE/DELETE 一律 `RAISE G0006`），
--      本来也无从清理。真要做数据订正，那是**数据订正**：单独一条迁移，人工评审，⛔ 不夹在回滚里。
--
-- `IF EXISTS` 的取舍
-- ---------------------------------------------------------------
-- 派单要求「只 `DROP FUNCTION IF EXISTS`」。这里照办：回滚件可能在「正向没跑过」的库上执行，
-- 此时静默成功是**正确**语义（没有要回滚的东西），与 `0042`/`0043` 正向里「先
-- `to_regprocedure` 硬前置」的那类脚本不同 —— 那些是**部署闸门**，这里只是一次撤销。
--
-- 不碰什么
-- ---------------------------------------------------------------
--   · ⛔ 不动 `admin_audit_events` 的任何行、索引、触发器（append-only 仍在）；
--   · ⛔ 不改 `0017` / `0021` / `0041` / `0046` / `0047` 的正文（checksum）；
--   · ⛔ 不动 `deploy/postgres-cvm/sql/20-login-roles.sql` 的授权区域：它带「函数必须已存在」的
--     硬前置（`to_regprocedure` 判空即 `RAISE`），下次部署会**显式失败**，正是要的效果 ——
--     不会静默留下一条对空函数的 `GRANT`。
--   · ⛔ 不反向写 `state`：回滚的是**写入能力**，不是已经发生的停用。若回滚后有人被停用且
--     再也无法恢复，那是**回滚决策**的后果，必须由人显式处理（⛔ 不要在回滚脚本里偷偷复活账号）。
BEGIN;

DROP FUNCTION IF EXISTS public.disable_admin_account(uuid, uuid, uuid, integer, uuid, text);
DROP FUNCTION IF EXISTS public.enable_admin_account(uuid, uuid, uuid, integer, uuid, text);

COMMIT;
