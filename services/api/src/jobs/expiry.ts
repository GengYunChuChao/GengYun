/**
 * 作业读面「超时裁定」的**共享单一真源**。
 *
 * 为什么要有这个文件：同一个缺陷在合成域与 OCR 域是同一句话 —— 执行器缺席（进程重启、
 * 提供者卡死、store 抛错）时没有任何人把任务推到终态，`GET /jobs/{id}` 于是**永远**回报
 * `queued` / `running`，用户界面的「处理中」永不结束（合成域的口径见
 * `services/api/src/tts/service.ts:45-47`）。两个域各自定义一份宽限常量，就会变成
 * 「同一缺陷两种说法、两个数字」：改一处忘一处只在读面上显形，且最难被单测抓住。
 * 因此「宽限是多少」与「怎样算过期」放在这里，两域**只许**从这里取
 * （`tts/service.ts` 原样 re-export，既有 import 面不变）。
 *
 * 为什么是 5 秒：读面与执行器写的是同一行（谁先落终态由 store 的 CAS 判定），但两者不是
 * 同一时刻 —— `deadline_at` 是受理时按同一个时钟算出来的，落库还要经过一次事务／一次网络
 * 往返。5 秒足够吸收这些**毫秒级**抖动，又不至于让用户在「处理中」这一屏上白等。
 *
 * 宽限**不是**给提供者的额外时间：提供者的预算由 `deadline_at` 决定，执行器自己的 deadline
 * 竞速在到点时就该落终态；宽限只覆盖「截止前已经跑完、只是提交晚了几毫秒」的竞态窗口，
 * 把它让给执行器 —— 两边都只写 `timed_out`，因此谁赢都不改变用户看到的终态。
 *
 * 本文件是**纯函数**：不读时钟、不碰 store、不产生任何 IO。判定可单测，裁定动作（CAS 写入、
 * 是否通知历史端口）留在各域服务里，由域自己负责。
 */

/** 读面「超时裁定」的宽限（毫秒）。口径来自合成域先例（`tts/service.ts:45-47`、`:114`）。 */
export const JOB_EXPIRY_GRACE_MS = 5 * 1000;

/**
 * 截止时间是否已过期（`deadline_at + 宽限` 之后即过期）。
 *
 * **含等号**：`at === deadlineAt + graceMs` 这一刻就判过期。这不是随手取的边界：
 *   - 执行器侧的口径是「到点还没落终态 ⇒ 读面是唯一裁定者」，等号落在「宽限已经等满」这一侧；
 *   - 若排除等号，`at` 恰好等于边界时读面要再等一次请求才裁定，同一份数据会给出两个答案，
 *     读面就不再是「按同一份数据给出同一结论」。
 * 反向（`at < deadline + grace`）一律不裁定，把毫秒级的提交竞态让给执行器。
 *
 * `graceMs` 只在测试里显式传值（用来钉边界）；生产调用一律用默认值，避免出现第二份宽限。
 */
export function isDeadlineExpired(
  deadlineAt: Date,
  at: Date,
  graceMs: number = JOB_EXPIRY_GRACE_MS,
): boolean {
  return at.getTime() >= deadlineAt.getTime() + graceMs;
}
