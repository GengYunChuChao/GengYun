/**
 * GY-I07 · 把资料契约同步为小程序可 require 的 CommonJS 数据。
 *
 * 目的：小程序页面（CommonJS）不能直接 import 纯 ESM 的 packages/reference，
 * 也不能在共享源码里联网。为避免**手工复制导致资料漂移**，这里从唯一事实来源
 * `packages/knowledge/**` 生成 `miniprogram/data/*.js`（`module.exports = <json>`）。
 *
 * 用法：
 *   node tools/knowledge/build_miniprogram_data.mjs            # 生成/覆盖
 *   node tools/knowledge/build_miniprogram_data.mjs --check    # 只校验是否已同步（CI/卫生检查用）
 *
 * 边界：只读 packages/knowledge/**，不修改契约；生成物为机械转换，不含人工编辑内容。
 */

import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs';
import { resolve, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

// 与服务端**同一个** id 派生函数：`GET /herbicides/{id}` 的 `id` 就是它算出来的
// （packages/reference/records.mjs 的 toHerbicideContract）。两边各写一份派生必然漂移，
// 所以这里直接复用，不重写算法。
import { deterministicUuid } from '../../packages/reference/records.mjs';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
const outDir = resolve(root, 'miniprogram', 'data');

const MAPPINGS = [
  { src: 'packages/knowledge/catalog/crops.json', out: 'crops.js' },
  { src: 'packages/knowledge/catalog/species.json', out: 'species.js' },
  { src: 'packages/knowledge/catalog/sources.json', out: 'sources.js' },
  // 地区目录体积较大（102 条），小程序侧只保留 code/name/parent_code 三字段以减小包体。
  { src: 'packages/knowledge/catalog/regions-zhejiang.json', out: 'regions.js', project: projectRegions },
  // 名录记录的 `record_id`（gy-i03-hb-NNN）是**可读记录号**，不是接口 id：
  // `GET /herbicides/{id}` 的 params schema 要求 uuid（services/api/src/routes/knowledge.ts），
  // 直接把 record_id 当 id 用会 400。故生成时按服务端同一函数补出 `id`，见 projectHerbicides。
  { src: 'packages/knowledge/herbicides/records-2026.json', out: 'records-2026.js', project: projectHerbicides },
  // GY-I07 指挥侧结构化种子资料（整理稿，强制标注「待核实·非权威」）：
  // 随功能分支提交，供小程序离线展示；原始 docx/xlsx 不入仓。
  { src: 'db/seeds/gy-i07/herbicides.json', out: 'seed-herbicides.js' },
  { src: 'db/seeds/gy-i07/weeds.json', out: 'seed-weeds.js' },
  { src: 'db/seeds/gy-i07/weed_master.json', out: 'seed-weed-master.js' },
  { src: 'db/seeds/gy-i07/province_index.json', out: 'seed-province-index.js' },
  { src: 'db/seeds/gy-i07/control_timing.json', out: 'seed-control-timing.js' },
];

const HEADER = '// AUTO-GENERATED by tools/knowledge/build_miniprogram_data.mjs — do not edit by hand.\n// Source: %SRC% (packages/knowledge contract; single source of truth).\n';

const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;

/**
 * 名录投影：给每条记录补上服务端**同名同值**的 `id`（uuid），`record_id` 原样保留。
 *
 * 为什么必须补：随包名录只有 `record_id`（gy-i03-hb-NNN），而 `GET /herbicides/{id}` 的
 * params schema 是 `{type:'string', format:'uuid'}` —— 拿 record_id 拼路由必然 400。
 * `id` 的算法不在这里重写，直接调服务端同一函数 `deterministicUuid(record_id)`
 * （packages/reference/records.mjs 的 toHerbicideContract 就是这么产 id 的），
 * 于是「随包名录里一条记录的 id」与「`GET /herbicides` 返回的同一条记录的 id」逐字相等。
 *
 * 确定性：纯函数、不读时钟/环境，键序固定（`id` 在前，其余保持来源文件顺序），
 * 同输入同输出 ⇒ 可重复生成，`git diff` 稳定。
 * 幂等：来源若已带合法 uuid（将来由资料侧直接下发），原样保留，不再改派生值。
 */
function projectHerbicides(doc) {
  const records = (doc.records || []).map((record) => {
    const { id, ...rest } = record;
    const identity = UUID.test(String(id)) ? id : deterministicUuid(rest.record_id);
    return { id: identity, ...rest };
  });
  return { ...doc, records };
}

/** 地区投影：只保留展示与筛选必需字段，附带 catalog_version。 */
function projectRegions(doc) {
  const regions = (doc.regions || doc.items || []).map((r) => ({
    code: r.code,
    name: r.name,
    parent_code: r.parent_code ?? null,
  }));
  return {
    schema: doc.schema,
    catalog_version: doc.catalog_version,
    region_count: doc.region_count ?? regions.length,
    regions,
  };
}

function render(srcRel, outFile, project) {
  const raw = JSON.parse(readFileSync(resolve(root, srcRel), 'utf8'));
  const value = project ? project(raw) : raw;
  const json = JSON.stringify(value, null, 2);
  return HEADER.replace('%SRC%', srcRel) + 'module.exports = ' + json + ';\n';
}

function main() {
  const check = process.argv.includes('--check');
  let drift = 0;
  if (!check && !existsSync(outDir)) mkdirSync(outDir, { recursive: true });

  for (const m of MAPPINGS) {
    const expected = render(m.src, m.out, m.project);
    const target = resolve(outDir, m.out);
    if (check) {
      const actual = existsSync(target) ? readFileSync(target, 'utf8') : '';
      // Git may check out generated text as CRLF on Windows. Only normalize
      // CRLF pairs: retain whitespace, bare CR, BOM, ordering and escaped data.
      if (actual.replace(/\r\n/g, '\n') !== expected) {
        console.error(`[drift] miniprogram/data/${m.out} 与 ${m.src} 不同步`);
        drift += 1;
      }
      continue;
    }
    writeFileSync(target, expected);
    console.log(`wrote miniprogram/data/${m.out}  <- ${m.src}`);
  }

  if (check) {
    if (drift > 0) {
      console.error(`FAIL：${drift} 个文件与资料契约不同步。请运行 node tools/knowledge/build_miniprogram_data.mjs`);
      process.exit(1);
    }
    console.log('OK：miniprogram/data 与 packages/knowledge 契约一致');
  }
}

main();
