/**
 * GY-I05（#5）手选清单可追溯性：作物／地区只能来自登记闭集，且小程序侧副本必须是
 * 机械生成物而不是手写列表。
 *
 * 背景：#5 要求「手动选择：地区列表来源必须真实可追溯，不得硬编码不可核对的清单」。
 * 仓库事实链是：民政部《2023年中华人民共和国县以上行政区划代码》（catalog_version
 * mca-xzqh-2023）→ packages/knowledge/catalog/*.json（唯一事实来源）→
 *   ① tools/knowledge/build_miniprogram_data.mjs 机械生成 miniprogram/data/*.js；
 *   ② db 种子 → public.regions → GET /api/v1/catalog/regions（页面手选实际取数）。
 * 本文件不复制期望值清单，而是用**独立实现**重算生成物并逐字比对；手改、漏字段、
 * 顺序漂移、版本漂移都会红。反例用变异文本证明这道闸门本身有效。
 */
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import { dirname, resolve } from 'node:path';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..', '..');
// 只归一 CRLF（Windows 检出），保留空白、顺序与转义，与工具 --check 的判据一致。
const read = relative => readFileSync(resolve(root, relative), 'utf8').replace(/\r\n/g, '\n');
const CROP_SOURCE = 'packages/knowledge/catalog/crops.json';
const REGION_SOURCE = 'packages/knowledge/catalog/regions-zhejiang.json';
const HEADER = '// AUTO-GENERATED by tools/knowledge/build_miniprogram_data.mjs — do not edit by hand.\n'
  + '// Source: %SRC% (packages/knowledge contract; single source of truth).\n';

function render(source) {
  const doc = JSON.parse(read(source));
  const regions = doc.regions.map(item => ({ code: item.code, name: item.name, parent_code: item.parent_code ?? null }));
  const projected = { schema: doc.schema, catalog_version: doc.catalog_version, region_count: doc.region_count ?? regions.length, regions };
  return { projected, text: HEADER.replace('%SRC%', source) + 'module.exports = ' + JSON.stringify(projected, null, 2) + ';\n' };
}
/** 闸门自身：给定任意文本，判断它是否等于「从唯一事实来源重算出来的那一份」。 */
const inSync = text => text === render(REGION_SOURCE).text;

test('手选地区副本与登记目录逐字一致：只含 code/name/parent_code，版本与条数同源', () => {
  const actual = read('miniprogram/data/regions.js');
  const { projected, text } = render(REGION_SOURCE);
  assert.equal(actual, text, 'miniprogram/data/regions.js 已偏离 packages/knowledge 登记目录（手改或未重新生成）');

  // 结构层面再核一遍，避免「两边一起错」。
  const doc = JSON.parse(read(REGION_SOURCE));
  const codes = new Set(projected.regions.map(item => item.code));
  assert.deepEqual(Object.keys(projected).sort(), ['catalog_version', 'region_count', 'regions', 'schema']);
  assert.equal(projected.catalog_version, 'mca-xzqh-2023');
  assert.equal(projected.region_count, projected.regions.length);
  assert.equal(projected.regions.length, doc.region_count);
  for (const item of projected.regions) {
    assert.deepEqual(Object.keys(item).sort(), ['code', 'name', 'parent_code']);
    assert.match(item.code, /^33[0-9]{4}$/, `${item.code} 不是浙江（33 开头）行政区划代码`);
    assert.equal(typeof item.name, 'string');
    if (item.parent_code !== null) assert.ok(codes.has(item.parent_code), `${item.code} 的 parent_code ${item.parent_code} 不在目录内`);
  }
  assert.equal(new Set(projected.regions.map(item => item.code)).size, projected.regions.length, '地区代码重复');
  assert.equal(projected.regions.filter(item => item.parent_code === null).length, 1, '只应有一个省级根节点');
});

test('闸门反例：手写清单、少字段、改版本、换顺序、缺声明头一律判为不同步', () => {
  const { projected, text } = render(REGION_SOURCE);
  const rebuild = value => HEADER.replace('%SRC%', REGION_SOURCE) + 'module.exports = ' + JSON.stringify(value, null, 2) + ';\n';
  // 正控制：原样重算必须判同步（否则下面的反例没有意义）。
  assert.equal(inSync(text), true);

  const forged = [...projected.regions, { code: '330199', name: '某虚构县', parent_code: '330100' }];
  assert.equal(inSync(rebuild({ ...projected, regions: forged, region_count: forged.length })), false, '额外塞入未登记县区应被挡下');
  assert.equal(inSync(rebuild({ ...projected, regions: projected.regions.map(item => ({ code: item.code, parent_code: item.parent_code })) })), false, '漏掉 name 应被挡下');
  assert.equal(inSync(rebuild({ ...projected, catalog_version: 'mca-xzqh-2019' })), false, '版本漂移应被挡下');
  assert.equal(inSync(rebuild({ ...projected, regions: [...projected.regions].reverse() })), false, '顺序漂移应被挡下');
  assert.equal(inSync(rebuild(projected).replace('// AUTO-GENERATED', '// 手工维护')), false, '手写（无生成声明）应被挡下');
  assert.equal(inSync(rebuild(projected).replace('"杭州市"', '"杭州"')), false, '改地名应被挡下');
});

test('作物闭集同源：小程序侧 4 类作物与 packages/knowledge 一致，且与服务端快照校验同源', () => {
  const source = JSON.parse(read(CROP_SOURCE));
  const actual = JSON.parse(read('miniprogram/data/crops.js').replace(/^[\s\S]*?module\.exports = /, '').replace(/;\n$/, ''));
  assert.deepEqual(actual, source, 'miniprogram/data/crops.js 已偏离 packages/knowledge/catalog/crops.json');
  assert.equal(source.crops.length, 4, '#5 范围是 4 类作物');
  assert.deepEqual(source.crops.map(item => item['id']), ['crop_rice', 'crop_corn', 'crop_soybean', 'crop_rapeseed']);

  // 服务端判定闭集时用的是同一份 JSON，不是另一份手抄常量。
  const service = read('services/api/src/profile/service.ts');
  assert.match(service, /packages\/knowledge\/catalog\/crops\.json/, '服务端作物闭集必须读登记目录');
  assert.match(service, /packages\/knowledge\/catalog\/regions-zhejiang\.json/, '服务端地区闭集必须读登记目录');
  assert.doesNotMatch(service, /'3301\d\d'|"3301\d\d"/, '服务端不应出现手抄的地区代码常量');
});

test('构建工具自检（--check）在本仓库为绿：登记目录与全部小程序生成物无漂移', () => {
  const result = spawnSync(process.execPath, [resolve(root, 'tools/knowledge/build_miniprogram_data.mjs'), '--check'], { cwd: root, encoding: 'utf8' });
  assert.equal(result.status, 0, `--check 失败：\n${result.stdout || ''}${result.stderr || ''}`);
  assert.match(result.stdout, /OK：miniprogram\/data 与 packages\/knowledge 契约一致/);
});
